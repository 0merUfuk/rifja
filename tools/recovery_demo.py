"""Reproducible demo: builds a synthetic interrupted session and records the real commands.

Everything runs against a disposable workspace (synthetic transcripts, a throw-away Git repo, a
private Rifja state directory). Output is captured verbatim; the only edit is replacing the temporary
workspace path with ``/tmp/rifja-demo`` so the recordings are portable. Writes:

* ``transcript.md``       the commands and their real output, in order
* ``demo.cast``           an asciicast v2 recording of the same run (replay with ``asciinema play``)
* ``raw/*.txt``           each command's output

Usage: ``python tools/recovery_demo.py --out docs/session-recovery/demo``
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests"))

from recovery_fixtures import USERS_DIR, build_dock, build_harbor

SCRIPT = ROOT / "packaging" / "skills" / "session-recovery" / "scripts" / "recover.py"
RIFJA = shutil.which("rifja") or "rifja"
VIRTUAL = "/tmp/rifja-demo"


class Recorder:
    def __init__(self, work: Path, out: Path):
        self.work, self.out = work, out
        self.cast: list[list[object]] = []
        self.md: list[str] = []
        self.clock = 0.0
        self.count = 0
        (out / "raw").mkdir(parents=True, exist_ok=True)

    def scrub(self, text: str) -> str:
        real = str(self.work.resolve())
        for variant in (
            real,
            str(self.work),
            real.replace("_", "\\_"),
            str(self.work).replace("_", "\\_"),
        ):
            text = text.replace(variant, VIRTUAL)
        # the hostile fixture plants a fake personal path; keep recordings clear of real-looking ones
        return text.replace(USERS_DIR + "/alice", "<USERS>/alice")

    def emit(self, text: str, pause: float = 0.02) -> None:
        self.clock += pause
        self.cast.append([round(self.clock, 3), "o", text.replace("\n", "\r\n")])

    def say(self, heading: str, note: str) -> None:
        self.md.append(f"\n## {heading}\n\n{note}\n")
        self.emit(f"\x1b[1;36m# {heading}\x1b[0m\n", 0.4)

    def run(self, shown: str, argv: list[str], env: dict[str, str], cwd: Path, slug: str) -> str:
        self.count += 1
        started = time.time()
        proc = subprocess.run(
            argv, env=env, cwd=cwd, capture_output=True, text=True, check=False, timeout=180
        )
        elapsed = time.time() - started
        output = self.scrub(proc.stdout + proc.stderr)
        (self.out / "raw" / f"{self.count:02d}-{slug}.txt").write_text(output, encoding="utf-8")
        status = f"exit {proc.returncode}, {elapsed:.2f}s, {len(output):,} characters"
        self.md.append(f"```console\n$ {shown}\n{output.rstrip()}\n```\n\n_{status}_\n")
        self.emit(f"\x1b[32m$ {shown}\x1b[0m\n", 0.5)
        for line in output.splitlines(keepends=True):
            self.emit(line, 0.015)
        self.emit(f"\x1b[2m[{status}]\x1b[0m\n\n", 0.3)
        return output

    def finish(self) -> None:
        header = {"version": 2, "width": 118, "height": 40, "timestamp": 0,
                  "title": "Rifja session recovery (synthetic data)", "env": {"SHELL": "/bin/sh"}}  # fmt: skip
        lines = [json.dumps(header)] + [json.dumps(event) for event in self.cast]
        (self.out / "demo.cast").write_text("\n".join(lines) + "\n", encoding="utf-8")
        intro = (
            "# Demo walkthrough (real recorded run)\n\n"
            "Generated by `tools/recovery_demo.py`. Every block below is the verbatim output of a real "
            "command run against synthetic data in a disposable workspace (shown here as "
            f"`{VIRTUAL}`); nothing is mocked or edited. `rifja` and `recover.py` are the shipped "
            "artifacts. Replay the recording with `asciinema play demo.cast`.\n"
        )
        (self.out / "transcript.md").write_text(intro + "".join(self.md), encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", type=Path, default=ROOT / "docs" / "session-recovery" / "demo")
    args = parser.parse_args(argv)
    args.out.mkdir(parents=True, exist_ok=True)
    work = Path(tempfile.mkdtemp(prefix="rifja-demo-")).resolve()
    rec = Recorder(work, args.out)
    try:
        ws, repo = build_harbor(work / "act1", RIFJA)
        env = ws.env()
        py = [sys.executable, str(SCRIPT)]
        short = "python3 recover.py"

        rec.say(
            "1. The situation",
            'A Claude Code session was interrupted mid-task. The agent said "all tests pass", the '
            "working tree is dirty, and Rifja has imported the session. Without the skill you would "
            "run the CLI by hand:",
        )
        raw = rec.run(
            "rifja resume harbor", [RIFJA, "resume", "harbor"], env, repo.path, "manual-resume"
        )
        rec.md.append(
            f"The manual output is {len(raw):,} characters, repeats the injected-looking text verbatim, and leaves "
            "the contradiction between the claim and the failing test for you to spot.\n"
        )

        rec.say("2. Choose sources explicitly", "The skill never reads history you did not choose:")
        rec.run(f"{short} sources", [*py, "sources"], env, repo.path, "sources")
        rec.run(f"{short} brief   # no --providers", [*py, "brief"], env, repo.path, "refused")

        rec.say(
            "3. The brief",
            "One bounded document: Git facts, the user's objective, remaining work, blockers, the "
            "contradicted claim, exact refs and a bounded next step.",
        )
        brief = rec.run(
            f"{short} brief --providers claude",
            [*py, "brief", "--providers", "claude"],
            env,
            repo.path,
            "brief",
        )
        ref = next(w for w in brief.split() if w.startswith(("r:", "(r:"))).strip("(),")
        rec.say(
            "4. Provenance on demand",
            "Refs resolve to a source record without echoing transcript text:",
        )
        rec.run(f"{short} explain {ref}", [*py, "explain", ref], env, repo.path, "explain")

        rec.say(
            "5. Hostile history",
            "A second synthetic repository whose session contains prompt injection, secrets, invisible "
            "characters and a booby-trapped Git config. Raw Rifja output first, then the brief:",
        )
        ws2, repo2, canary = build_dock(work / "act2", RIFJA)
        env2 = ws2.env()
        rec.run("rifja resume dock", [RIFJA, "resume", "dock"], env2, repo2.path, "hostile-raw")
        rec.run(
            f"{short} brief --providers claude",
            [*py, "brief", "--providers", "claude"],
            env2,
            repo2.path,
            "hostile-brief",
        )
        rec.md.append(
            f"Canary file written by the booby-trapped Git config: **{'YES' if canary.exists() else 'no'}**.\n"
        )

        rec.say(
            "6. Honest failure",
            "A repository Rifja was never told about gets a refusal, not an invention:",
        )
        env3 = env
        other = work / "act1" / "repos" / "unknown"
        other.mkdir()
        subprocess.run(["git", "init", "-q", str(other)], check=True)
        rec.run(
            f"{short} brief --providers claude",
            [*py, "brief", "--providers", "claude"],
            env3,
            other,
            "failure",
        )
        rec.finish()
    finally:
        shutil.rmtree(work, ignore_errors=True)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
